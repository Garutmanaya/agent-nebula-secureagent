"""Public SecureAgent facade for correlated Platform execution tracing.

SecureAgent deliberately exposes only the lifecycle boundary needed by an
application host. Agent Nebula Platform remains responsible for creating the
low-level, transport/security-aware events generated by discovery, OAuth,
DPoP, Agent Card resolution, and A2A operations. The application remains
responsible for choosing the execution identifier and deciding how the
already-sanitized events are persisted or rendered.

Keeping this context manager in SecureAgent prevents application code from
importing Platform implementation primitives directly while preserving one
correlation context across all nested Platform operations.
"""

from __future__ import annotations

from collections.abc import Callable, Iterator, Mapping
from contextlib import contextmanager
from typing import Any

from agent_nebula_platform.platform.execution_trace import (
    activate_execution_trace,
    reset_execution_trace,
)

ExecutionTraceRecorder = Callable[[Mapping[str, Any]], None]


@contextmanager
def execution_trace(
    execution_id: str,
    *,
    recorder: ExecutionTraceRecorder,
) -> Iterator[None]:
    """Correlate nested SecureAgent/Platform operations with one host execution.

    This function provides the public execution-trace boundary for applications
    built on SecureAgent. While the context is active, Platform operations can:

    * attach the same execution identifier to supported outbound requests;
    * emit semantic events for discovery, Agent Card, OAuth/DPoP, and A2A work;
    * redact sensitive security material before an event reaches ``recorder``;
    * forward those sanitized events to the host without coupling Platform to
      the host's persistence, workflow, or user-interface implementation.

    SecureAgent does not create or persist the execution identifier and does
    not perform a second interpretation of Platform events. The caller owns the
    trace lifecycle and supplies the recorder used by its observability model.

    Args:
        execution_id: Host-owned correlation identifier shared by all nested
            Platform operations executed inside this context. Leading/trailing
            whitespace is ignored and a blank identifier is rejected.
        recorder: Host callback that receives sanitized Platform event
            mappings. Each event is copied before forwarding so host code cannot
            mutate the Platform-owned event object.

    Raises:
        ValueError: If ``execution_id`` is empty or contains only whitespace.

    Notes:
        The previous Platform context is restored in ``finally``. This makes
        nesting safe and prevents a failed workflow from leaking its execution
        correlation into later requests handled by the same process/context.
    """

    normalized_execution_id = execution_id.strip()
    if not normalized_execution_id:
        raise ValueError("execution_id must not be blank")

    def forward(event: dict[str, Any]) -> None:
        # Platform has already applied its security redaction boundary. Copying
        # here protects the Platform-owned event object from host-side mutation.
        recorder(dict(event))

    token = activate_execution_trace(normalized_execution_id, recorder=forward)
    try:
        yield
    finally:
        # Always restore the prior ContextVar token, including exception paths.
        # This is required for nested traces and long-lived async server workers.
        reset_execution_trace(token)
